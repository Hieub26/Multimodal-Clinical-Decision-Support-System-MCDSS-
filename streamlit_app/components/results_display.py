"""
Results display component for diagnosis output.
"""

import json
import streamlit as st
from PIL import Image
from pathlib import Path


def _build_clinical_explanation(base_explanation: str, vlm_review: dict | None) -> str:
    """Append structured VLM safety reasoning to the clinical explanation."""
    sections = [base_explanation] if base_explanation else []
    if not vlm_review:
        return "\n\n".join(sections)

    vlm_lines = []
    risk_level = vlm_review.get("risk_level")
    if risk_level:
        vlm_lines.append(f"Risk level: {risk_level}")

    reasoning = vlm_review.get("reasoning")
    if reasoning:
        vlm_lines.append(f"VLM reasoning: {reasoning}")

    if vlm_lines:
        sections.append("VLM safety review:\n" + "\n".join(f"- {line}" for line in vlm_lines))

    return "\n\n".join(sections)


def render_results(response: dict, gradcam_path: str = None):
    """Render the full diagnosis results."""
    if not response:
        cv = response.get("cv_details")
        if cv:
            with st.expander("Computer Vision Debug Details", expanded=True):
                st.markdown(f"**Predicted Class:** {cv.get('predicted_class', 'N/A')}")
                st.markdown(f"**Confidence:** {cv.get('confidence', 0):.1%}")
                st.markdown(f"**Abnormality Score:** {cv.get('abnormality_score', 0):.1%}")
                st.markdown(f"**Decision Threshold:** {cv.get('decision_threshold', 0):.1%}")

                preds = cv.get("top_predictions", [])
                if preds:
                    st.markdown("**Top Raw Class Probabilities:**")
                    for p in preds:
                        st.markdown(
                            f"- {p.get('class', 'Unknown')}: "
                            f"{p.get('probability', 0):.1%}"
                        )
        return

    st.markdown("""
    <div class="section-header animate-in">
        <h2>🔍 Diagnosis Results</h2>
    </div>
    """, unsafe_allow_html=True)

    diagnosis = response.get("diagnosis", {})
    safety = response.get("safety", {})
    validation = response.get("validation", {})

    # === Safety Banner ===
    if safety.get("is_approved"):
        st.markdown(f"""
        <div class="safety-banner safety-approved animate-in">
            ✅ <b>APPROVED OUTPUT</b> — {safety.get("message", "")}
        </div>
        """, unsafe_allow_html=True)
    else:
        st.markdown(f"""
        <div class="safety-banner safety-fallback animate-in">
            ⚠️ <b>CONSULT A DOCTOR</b> — {safety.get("message", "")}
        </div>
        """, unsafe_allow_html=True)

        # When not approved, only show disclaimer and return early
        st.markdown("""
        <div class="disclaimer">
            ⚕️ <b>DISCLAIMER:</b> This analysis is generated by an AI system for educational 
            purposes only. It is NOT a substitute for professional medical advice. Always consult 
            a qualified healthcare provider for medical decisions.
        </div>
        """, unsafe_allow_html=True)
        return

    # === Everything below only shows when APPROVED ===

    # === Primary Diagnosis Card ===
    confidence = diagnosis.get("confidence", 0)
    severity = diagnosis.get("severity", "unknown")
    urgency = diagnosis.get("urgency", "routine")

    severity_colors = {
        "low": "#22c55e", "moderate": "#f59e0b",
        "high": "#ef4444", "critical": "#dc2626",
    }
    sev_color = severity_colors.get(severity, "#94a3b8")

    st.markdown(f"""
    <div class="diagnosis-primary animate-in">
        <h3>Primary Diagnosis</h3>
        <div class="diagnosis-name">{diagnosis.get("primary_diagnosis", "N/A")}</div>
    </div>
    """, unsafe_allow_html=True)

    # === Metrics Row ===
    col1, col2, col3, col4 = st.columns(4)

    with col1:
        st.markdown(f"""
        <div class="metric-card">
            <div class="metric-value">{confidence:.0%}</div>
            <div class="metric-label">Confidence</div>
        </div>
        """, unsafe_allow_html=True)

    with col2:
        st.markdown(f"""
        <div class="metric-card">
            <div class="metric-value" style="color: {sev_color};">{severity.upper()}</div>
            <div class="metric-label">Severity</div>
        </div>
        """, unsafe_allow_html=True)

    with col3:
        urgency_color = "#ef4444" if urgency in ("urgent", "emergency") else "#f59e0b" if urgency == "urgent" else "#22c55e"
        st.markdown(f"""
        <div class="metric-card">
            <div class="metric-value" style="color: {urgency_color};">{urgency.upper()}</div>
            <div class="metric-label">Urgency</div>
        </div>
        """, unsafe_allow_html=True)

    with col4:
        modality = response.get("modality", "unknown")
        st.markdown(f"""
        <div class="metric-card">
            <div class="metric-value" style="font-size: 1.2rem;">{modality.upper()}</div>
            <div class="metric-label">Modality</div>
        </div>
        """, unsafe_allow_html=True)

    # === Clinical Question Answer ===
    question_answer = diagnosis.get("question_answer", "")
    if question_answer and question_answer.strip().upper() != "N/A":
        st.markdown("---")
        st.markdown("#### 💬 Clinical Question Answer")
        st.markdown(f"""
        <div style="padding: 16px 20px; background: rgba(59, 130, 246, 0.08);
                    border-left: 4px solid #3b82f6; border-radius: 8px;
                    color: #e2e8f0; line-height: 1.7;">
            {question_answer}
        </div>
        """, unsafe_allow_html=True)

    # === Clinical Explanation ===
    explanation = _build_clinical_explanation(
        diagnosis.get("explanation", ""),
        response.get("vlm_safety_review"),
    )
    if explanation:
        st.markdown("---")
        st.markdown("#### 📋 Clinical Explanation")
        st.info(explanation)

    # === Recommended Actions ===
    actions = diagnosis.get("recommended_actions", [])
    if actions:
        st.markdown("#### ✅ Recommended Actions")
        for action in actions:
            st.markdown(f"""
            <div style="display: flex; align-items: center; gap: 10px; padding: 8px 14px;
                        margin-bottom: 6px; background: rgba(34, 197, 94, 0.08);
                        border-left: 3px solid #22c55e; border-radius: 6px;">
                <span style="color: #22c55e; font-size: 1.1rem;">→</span>
                <span style="color: #e2e8f0;">{action}</span>
            </div>
            """, unsafe_allow_html=True)

    # === NLP Details ===
    nlp = response.get("nlp_details")
    if nlp:
        with st.expander("🧠 NLP Analysis Details", expanded=False):
            st.markdown(f"**Primary Diagnosis:** {nlp.get('primary_diagnosis', 'N/A')}")
            st.markdown(f"**Confidence:** {nlp.get('confidence', 0):.0%}")

            nlp_explanation = nlp.get("explanation", "")
            if nlp_explanation:
                st.markdown("**Explanation:**")
                st.info(nlp_explanation)

            # Differential diagnoses
            diffs = nlp.get("differential_diagnoses", [])
            if diffs:
                st.markdown("**Differential Diagnoses:**")
                for d in diffs:
                    prob = d.get("probability", 0)
                    name = d.get("condition", "Unknown")
                    st.markdown(f"""
                    <div class="prob-bar-container">
                        <div class="prob-bar-label">
                            <span style="color: #f0f4f8;">{name}</span>
                            <span style="color: #94a3b8;">{prob:.0%}</span>
                        </div>
                        <div class="prob-bar-track">
                            <div class="prob-bar-fill" style="width: {prob*100}%;"></div>
                        </div>
                    </div>
                    """, unsafe_allow_html=True)

            # Supporting evidence
            evidence = nlp.get("supporting_evidence", [])
            if evidence:
                st.markdown("**Supporting Evidence:**")
                for e in evidence:
                    st.markdown(f"- {e}")

    # === CV Details ===
    cv = response.get("cv_details")
    if cv:
        with st.expander("🩻 Computer Vision Analysis", expanded=False):
            st.markdown(f"**Predicted Class:** {cv.get('predicted_class', 'N/A')}")
            st.markdown(f"**Confidence:** {cv.get('confidence', 0):.0%}")

            # Top predictions
            preds = cv.get("top_predictions", [])
            if preds:
                st.markdown("**Class Probabilities:**")
                for p in preds:
                    prob = p.get("probability", 0)
                    name = p.get("class", "Unknown")
                    st.markdown(f"""
                    <div class="prob-bar-container">
                        <div class="prob-bar-label">
                            <span style="color: #f0f4f8;">{name}</span>
                            <span style="color: #94a3b8;">{prob:.0%}</span>
                        </div>
                        <div class="prob-bar-track">
                            <div class="prob-bar-fill" style="width: {prob*100}%;"></div>
                        </div>
                    </div>
                    """, unsafe_allow_html=True)

            # === Grad-CAM inside CV expander ===
            if gradcam_path and Path(gradcam_path).exists():
                st.markdown("---")
                st.markdown("**🔥 Grad-CAM Explainability**")
                st.markdown("""
                <p style="color: #94a3b8; font-size: 0.85rem; margin: 4px 0 10px 0;">
                    Grad-CAM highlights regions that most influenced the model's prediction.
                    Warmer colors (red/yellow) indicate areas of higher importance.
                </p>
                """, unsafe_allow_html=True)
                gradcam_image = Image.open(gradcam_path)
                st.image(
                    gradcam_image,
                    caption="Original | Grad-CAM Heatmap | Overlay",
                    width="stretch",
                )

    # === Validation Details ===
    with st.expander("📏 Guideline Validation", expanded=False):
        consistent = validation.get("guideline_consistent", False)
        support = validation.get("support_score", 0)

        status_html = (
            '<span class="badge badge-safe">✓ Consistent</span>'
            if consistent
            else '<span class="badge badge-warning">⚠ Needs Review</span>'
        )
        st.markdown(f"**Status:** {status_html}", unsafe_allow_html=True)
        st.markdown(f"**Support Score:** {support:.0%}")

        for note in validation.get("notes", []):
            st.markdown(f"- {note}")

    # === Risk Factors ===
    risk_factors = safety.get("risk_factors", [])
    if risk_factors:
        with st.expander("🛡️ Risk Factors", expanded=False):
            for rf in risk_factors:
                st.warning(rf)

    # === JSON Output ===
    with st.expander("📄 Structured JSON Output", expanded=False):
        st.json(response)

    # === Disclaimer ===
    st.markdown("""
    <div class="disclaimer">
        ⚕️ <b>DISCLAIMER:</b> This analysis is generated by an AI system for educational 
        purposes only. It is NOT a substitute for professional medical advice. Always consult 
        a qualified healthcare provider for medical decisions.
    </div>
    """, unsafe_allow_html=True)
